type Input = Omit<Product, 'discount' | 'id' | 'sizes' | 'care' | 'colors'> & {
  sizes?: Size[]
  care?: string[]
  colors: ProductColor[]
}

let counter = 0
function define(input: Input): Product {
  counter += 1
  const isBottom = input.category === 'pants'
  return {
    ...input,
    id: `SU${String(2600 + counter)}`,
    sizes: input.sizes ?? (isBottom ? WAIST : TOP),
    care: input.care ?? CARE.cotton,
    discount: discountPercent(input.price, input.originalPrice),
    images: input.colors[0]?.images ?? input.images,
  }
}

