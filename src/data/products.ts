export const productById = new Map(products.map((p) => [p.id, p]))
export const productBySlug = new Map(products.map((p) => [p.slug, p]))

export const getProduct = (slug?: string) => (slug ? productBySlug.get(slug) : undefined)
export const isSoldOut = (p: Product) => p.stock <= 0
export const isLowStock = (p: Product) => p.stock > 0 && p.stock <= 9

export const newArrivals = () => products.filter((p) => p.newArrival)
export const bestSellers = () => products.filter((p) => p.bestSeller).sort((a, b) => b.reviewCount - a.reviewCount)
export const onSale = () => products.filter((p) => p.discount)
export const limitedEdition = () => products.filter((p) => p.limited)
export const byCategory = (slug: CategorySlug) => products.filter((p) => p.category === slug)
export const byCollection = (slug: string) => products.filter((p) => p.collection === slug)
export const byTag = (tag: string) => products.filter((p) => p.tags.includes(tag))

export function relatedProducts(product: Product, limit = 8): Product[] {
  const score = (p: Product) =>
    (p.category === product.category ? 3 : 0) +
    (p.collection === product.collection ? 2 : 0) +
    p.tags.filter((t) => product.tags.includes(t)).length
  return products
    .filter((p) => p.id !== product.id && !isSoldOut(p))
    .map((p) => ({ p, s: score(p) }))
    .sort((a, b) => b.s - a.s || b.p.rating - a.p.rating)
    .slice(0, limit)
    .map(({ p }) => p)
}

export function searchProducts(query: string, limit?: number): Product[] {
  const q = query.trim().toLowerCase()
  if (!q) return []
  const terms = q.split(/\s+/)
  const results = products
    .map((p) => {
      const hay = [p.name, p.category, p.subcategory, p.collection, p.fit, p.material, ...p.tags, ...p.colors.map((c) => c.name)]
        .join(' ')
        .toLowerCase()
        .replace(/-/g, ' ')
      const all = terms.every((t) => hay.includes(t) || hay.includes(t.replace(/s$/, '')))
      if (!all) return null
      const nameHit = terms.filter((t) => p.name.toLowerCase().includes(t)).length
      return { p, s: nameHit * 10 + p.rating }
    })
    .filter((x): x is { p: Product; s: number } => x !== null)
    .sort((a, b) => b.s - a.s)
    .map((x) => x.p)
  return limit ? results.slice(0, limit) : results
}

